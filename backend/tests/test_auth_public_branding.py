from app.auth.middleware import _is_public_request


def test_branding_reads_are_public():
    assert _is_public_request("GET", "/api/settings/branding") is True
    assert _is_public_request("GET", "/api/settings/branding/logo") is True


def test_branding_mutations_are_not_public():
    assert _is_public_request("PUT", "/api/settings/branding/palette") is False
    assert _is_public_request("DELETE", "/api/settings/branding/palette") is False
    assert _is_public_request("PUT", "/api/settings/branding/logo") is False
    assert _is_public_request("DELETE", "/api/settings/branding/logo") is False


def test_query_string_does_not_change_public_logo_path_behavior():
    # Starlette/FastAPI request.url.path excludes the query string. This mirrors
    # the browser request generated by customLogoUrl(...?v=<timestamp>).
    assert _is_public_request("GET", "/api/settings/branding/logo") is True
