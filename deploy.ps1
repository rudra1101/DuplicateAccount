param(
    [ValidateSet("lan", "https")]
    [string]$Mode = "lan",

    [string]$Domain = "",

    [ValidateRange(1, 65535)]
    [int]$Port = 8080,

    [switch]$Monitoring,
    [switch]$SetupAI,
    [switch]$OpenFirewall,
    [switch]$SkipBuild,
    [switch]$NoOpen
)

$ErrorActionPreference = "Stop"
Set-StrictMode -Version Latest

$RepoRoot = Split-Path -Parent $MyInvocation.MyCommand.Path
$EnvPath = Join-Path $RepoRoot "backend\.env"
$ComposeFile = Join-Path $RepoRoot "docker-compose.yml"
$HttpsComposeFile = Join-Path $RepoRoot "docker-compose.https.yml"

function Write-Step([string]$Message) {
    Write-Host "`n==> $Message" -ForegroundColor Cyan
}

function Write-Ok([string]$Message) {
    Write-Host "[OK] $Message" -ForegroundColor Green
}

function Write-Warn([string]$Message) {
    Write-Host "[WARN] $Message" -ForegroundColor Yellow
}

function New-HexSecret([int]$Bytes = 32) {
    $buffer = New-Object byte[] $Bytes
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try {
        $rng.GetBytes($buffer)
    }
    finally {
        $rng.Dispose()
    }
    return -join ($buffer | ForEach-Object { $_.ToString("x2") })
}

function Ensure-EnvFile {
    $directory = Split-Path -Parent $EnvPath
    if (-not (Test-Path $directory)) {
        New-Item -ItemType Directory -Force -Path $directory | Out-Null
    }
    if (-not (Test-Path $EnvPath)) {
        [System.IO.File]::WriteAllText(
            $EnvPath,
            "# Generated by deploy.ps1`r`n",
            (New-Object System.Text.UTF8Encoding($false))
        )
    }
}

function Get-EnvValue([string]$Key) {
    if (-not (Test-Path $EnvPath)) {
        return $null
    }

    $pattern = "^\s*" + [Regex]::Escape($Key) + "\s*=\s*(.*)$"
    foreach ($line in [System.IO.File]::ReadAllLines($EnvPath)) {
        if ($line -match $pattern) {
            return $Matches[1].Trim()
        }
    }
    return $null
}

function Set-EnvValue([string]$Key, [string]$Value) {
    Ensure-EnvFile
    $lines = [System.Collections.Generic.List[string]]::new()
    $lines.AddRange([string[]][System.IO.File]::ReadAllLines($EnvPath))

    $pattern = "^\s*" + [Regex]::Escape($Key) + "\s*="
    $updated = $false
    for ($i = 0; $i -lt $lines.Count; $i++) {
        if ($lines[$i] -match $pattern) {
            $lines[$i] = "$Key=$Value"
            $updated = $true
            break
        }
    }

    if (-not $updated) {
        if ($lines.Count -gt 0 -and $lines[$lines.Count - 1] -ne "") {
            $lines.Add("")
        }
        $lines.Add("$Key=$Value")
    }

    [System.IO.File]::WriteAllLines(
        $EnvPath,
        $lines,
        (New-Object System.Text.UTF8Encoding($false))
    )
}

function Get-LanIp {
    try {
        $configs = Get-NetIPConfiguration -ErrorAction Stop |
            Where-Object { $_.IPv4DefaultGateway -and $_.IPv4Address }

        foreach ($config in $configs) {
            foreach ($address in $config.IPv4Address) {
                $candidate = [string]$address.IPAddress
                if ($candidate -and
                    -not $candidate.StartsWith("127.") -and
                    -not $candidate.StartsWith("169.254.")) {
                    return $candidate
                }
            }
        }
    }
    catch {
        # The deployment still works locally if IP discovery is unavailable.
    }
    return $null
}

function Test-IsAdministrator {
    $identity = [Security.Principal.WindowsIdentity]::GetCurrent()
    $principal = New-Object Security.Principal.WindowsPrincipal($identity)
    return $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
}

function Invoke-Compose {
    param(
        [Parameter(Mandatory = $true)]
        [string[]]$Arguments,
        [switch]$Capture
    )

    $dockerArgs = @("compose", "--env-file", $EnvPath, "-f", $ComposeFile)
    if ($Mode -eq "https") {
        $dockerArgs += @("-f", $HttpsComposeFile)
    }
    if ($Monitoring) {
        $dockerArgs += @("--profile", "monitoring")
    }
    $dockerArgs += $Arguments

    if ($Capture) {
        $output = & docker @dockerArgs 2>&1
        if ($LASTEXITCODE -ne 0) {
            throw "docker compose failed: $($output -join [Environment]::NewLine)"
        }
        return ($output -join [Environment]::NewLine)
    }

    & docker @dockerArgs
    if ($LASTEXITCODE -ne 0) {
        throw "docker compose failed with exit code $LASTEXITCODE."
    }
}

function Wait-ServiceHealthy([string]$Service, [int]$TimeoutSeconds = 240) {
    $containerId = (Invoke-Compose -Arguments @("ps", "-q", $Service) -Capture).Trim()
    if (-not $containerId) {
        throw "No container was created for service '$Service'."
    }

    $deadline = (Get-Date).AddSeconds($TimeoutSeconds)
    do {
        $status = (& docker inspect --format '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}' $containerId 2>$null).Trim()
        if ($status -eq "healthy" -or $status -eq "running") {
            Write-Ok "$Service is $status."
            return
        }
        if ($status -eq "unhealthy" -or $status -eq "exited" -or $status -eq "dead") {
            Write-Warn "$Service is $status. Recent logs:"
            Invoke-Compose -Arguments @("logs", "--tail=100", $Service)
            throw "Service '$Service' failed to become healthy."
        }
        Start-Sleep -Seconds 3
    } while ((Get-Date) -lt $deadline)

    Write-Warn "$Service did not become healthy before timeout. Recent logs:"
    Invoke-Compose -Arguments @("logs", "--tail=100", $Service)
    throw "Timed out waiting for service '$Service'."
}

function Configure-Firewall {
    if (-not $OpenFirewall) {
        return
    }

    if (-not (Test-IsAdministrator)) {
        Write-Warn "Firewall rules were requested, but PowerShell is not running as Administrator."
        Write-Warn "Re-run as Administrator with -OpenFirewall if other machines cannot reach this host."
        return
    }

    if ($Mode -eq "lan") {
        $ruleName = "IdentityAI HTTP $Port"
        if (-not (Get-NetFirewallRule -DisplayName $ruleName -ErrorAction SilentlyContinue)) {
            New-NetFirewallRule -DisplayName $ruleName -Direction Inbound -Action Allow -Protocol TCP -LocalPort $Port | Out-Null
        }
        Write-Ok "Windows Firewall allows inbound TCP $Port."
    }
    else {
        foreach ($httpsPort in @(80, 443)) {
            $ruleName = "IdentityAI HTTPS $httpsPort"
            if (-not (Get-NetFirewallRule -DisplayName $ruleName -ErrorAction SilentlyContinue)) {
                New-NetFirewallRule -DisplayName $ruleName -Direction Inbound -Action Allow -Protocol TCP -LocalPort $httpsPort | Out-Null
            }
        }
        Write-Ok "Windows Firewall allows inbound TCP 80 and 443."
    }
}

Push-Location $RepoRoot
try {
    Write-Step "Checking prerequisites"

    & docker version *> $null
    if ($LASTEXITCODE -ne 0) {
        throw "Docker is not running. Start Docker Desktop and run this script again."
    }

    & docker compose version *> $null
    if ($LASTEXITCODE -ne 0) {
        throw "Docker Compose v2 is required. Update Docker Desktop and run this script again."
    }
    Write-Ok "Docker and Docker Compose are available."

    if ($Mode -eq "https") {
        $Domain = $Domain.Trim().ToLowerInvariant()
        if (-not $Domain) {
            throw "HTTPS mode requires -Domain, for example: .\deploy.ps1 -Mode https -Domain identity.example.com"
        }
        if ($Domain -match '^https?://' -or $Domain -match 'localhost' -or $Domain -notmatch '\.') {
            throw "Use a real DNS hostname only (for example identity.example.com), without http:// or https://."
        }
        $parsedIp = $null
        if ([System.Net.IPAddress]::TryParse($Domain, [ref]$parsedIp)) {
            throw "Automatic trusted HTTPS requires a DNS hostname, not an IP address. Use LAN mode for IP-based deployment."
        }
        if (-not (Test-Path $HttpsComposeFile)) {
            throw "docker-compose.https.yml is missing."
        }
    }

    Write-Step "Preparing deployment configuration"
    Ensure-EnvFile

    $postgresDb = Get-EnvValue "POSTGRES_DB"
    if (-not $postgresDb) { $postgresDb = "identityai" }

    $postgresUser = Get-EnvValue "POSTGRES_USER"
    if (-not $postgresUser) { $postgresUser = "identityai" }

    $postgresPassword = Get-EnvValue "POSTGRES_PASSWORD"
    if (-not $postgresPassword -or $postgresPassword -match '^replace-' -or $postgresPassword -match '^change-') {
        $postgresPassword = New-HexSecret 24
        Write-Ok "Generated a PostgreSQL password."
    }

    $authSecret = Get-EnvValue "AUTH_SECRET_KEY"
    if (-not $authSecret -or $authSecret.Length -lt 32 -or $authSecret -match '^replace-' -or $authSecret -match '^change-') {
        $authSecret = New-HexSecret 32
        Write-Ok "Generated an application authentication secret."
    }

    $hostName = [System.Net.Dns]::GetHostName()
    $lanIp = Get-LanIp

    Set-EnvValue "POSTGRES_DB" $postgresDb
    Set-EnvValue "POSTGRES_USER" $postgresUser
    Set-EnvValue "POSTGRES_PASSWORD" $postgresPassword
    Set-EnvValue "DATABASE_HOST" "postgres"
    Set-EnvValue "DATABASE_PORT" "5432"
    Set-EnvValue "DATABASE_NAME" $postgresDb
    Set-EnvValue "DATABASE_USER" $postgresUser
    Set-EnvValue "DATABASE_PASSWORD" $postgresPassword
    Set-EnvValue "AUTH_SECRET_KEY" $authSecret
    Set-EnvValue "AUTH_COOKIE_SAMESITE" "lax"
    Set-EnvValue "SECURITY_HEADERS_ENABLED" "true"
    Set-EnvValue "CORS_ORIGINS" ""
    Set-EnvValue "FRONTEND_PORT" ([string]$Port)

    if (-not (Get-EnvValue "DOCKER_OLLAMA_BASE_URL")) {
        Set-EnvValue "DOCKER_OLLAMA_BASE_URL" "http://host.docker.internal:11434"
    }

    if ($Mode -eq "lan") {
        $hosts = @("localhost", "127.0.0.1", "backend", "frontend", $hostName)
        if ($lanIp) { $hosts += $lanIp }
        $hosts = $hosts | Where-Object { $_ } | Select-Object -Unique

        Set-EnvValue "APP_ENV" "deployment"
        Set-EnvValue "AUTH_COOKIE_SECURE" "false"
        Set-EnvValue "ALLOWED_HOSTS" ($hosts -join ",")
        Set-EnvValue "FRONTEND_BIND_ADDRESS" "0.0.0.0"
        Write-Ok "Configured same-origin LAN deployment."
    }
    else {
        Set-EnvValue "APP_ENV" "production"
        Set-EnvValue "AUTH_COOKIE_SECURE" "true"
        Set-EnvValue "ALLOWED_HOSTS" "$Domain,backend,frontend"
        Set-EnvValue "FRONTEND_BIND_ADDRESS" "127.0.0.1"
        Set-EnvValue "APP_DOMAIN" $Domain
        Write-Ok "Configured production HTTPS deployment for $Domain."
        Write-Warn "DNS for $Domain must resolve to this machine and inbound TCP 80/443 must reach it for automatic certificate issuance."
    }

    if ($SetupAI) {
        Write-Step "Preparing Rudrix models"
        $ollama = Get-Command ollama -ErrorAction SilentlyContinue
        if (-not $ollama) {
            Write-Warn "Ollama is not installed on the host. Core IdentityAI deployment will continue without Rudrix."
        }
        else {
            & ollama pull llama3.1:8b
            if ($LASTEXITCODE -ne 0) { throw "Failed to pull llama3.1:8b." }
            & ollama pull nomic-embed-text
            if ($LASTEXITCODE -ne 0) { throw "Failed to pull nomic-embed-text." }
            Write-Ok "Rudrix models are present."
        }
    }

    Configure-Firewall

    Write-Step "Validating Docker configuration"
    Invoke-Compose -Arguments @("config", "--quiet")
    Write-Ok "Docker Compose configuration is valid."

    Write-Step "Starting IdentityAI"
    $upArgs = @("up", "-d")
    if (-not $SkipBuild) {
        $upArgs += "--build"
    }
    Invoke-Compose -Arguments $upArgs

    Write-Step "Waiting for services"
    Wait-ServiceHealthy "postgres" 120
    Wait-ServiceHealthy "backend" 240
    Wait-ServiceHealthy "frontend" 120

    if ($Mode -eq "https") {
        $caddyId = (Invoke-Compose -Arguments @("ps", "-q", "caddy") -Capture).Trim()
        if (-not $caddyId) {
            throw "HTTPS gateway container was not created."
        }
        $caddyStatus = (& docker inspect --format '{{.State.Status}}' $caddyId 2>$null).Trim()
        if ($caddyStatus -ne "running") {
            Invoke-Compose -Arguments @("logs", "--tail=100", "caddy")
            throw "HTTPS gateway is not running."
        }
        Write-Ok "HTTPS gateway is running."
    }

    Write-Step "Deployment complete"
    if ($Mode -eq "lan") {
        $localUrl = "http://localhost:$Port"
        Write-Host "Local URL: $localUrl" -ForegroundColor Green
        if ($lanIp) {
            Write-Host "LAN URL:   http://$lanIp`:$Port" -ForegroundColor Green
        }
        else {
            Write-Warn "LAN IP could not be detected automatically. Use ipconfig to find the host IPv4 address."
        }

        if (-not $OpenFirewall) {
            Write-Warn "If another machine cannot connect, re-run this script as Administrator with -OpenFirewall."
        }

        if (-not $NoOpen) {
            Start-Process $localUrl
        }
    }
    else {
        $publicUrl = "https://$Domain"
        Write-Host "HTTPS URL: $publicUrl" -ForegroundColor Green
        Write-Host "Local maintenance URL: http://localhost:$Port" -ForegroundColor DarkGray
        Write-Host "Caddy obtains and renews the public TLS certificate automatically." -ForegroundColor Green

        if (-not $OpenFirewall) {
            Write-Warn "Ensure TCP 80 and 443 are allowed through Windows/network firewalls."
        }

        if (-not $NoOpen) {
            Start-Process $publicUrl
        }
    }

    try {
        Invoke-RestMethod -Uri "http://127.0.0.1:11434/api/tags" -Method Get -TimeoutSec 3 | Out-Null
        Write-Ok "Ollama is reachable from the host."
    }
    catch {
        Write-Warn "Ollama is not reachable on port 11434. Core IdentityAI is healthy; Rudrix remains optional until Ollama is running."
    }

    Write-Host "`nUseful commands:" -ForegroundColor Cyan
    Write-Host "  .\deploy.ps1                    # LAN/demo deployment"
    Write-Host "  .\deploy.ps1 -SetupAI           # LAN deployment + ensure Rudrix models"
    Write-Host "  .\deploy.ps1 -Mode https -Domain identity.example.com"
    Write-Host "  docker compose --env-file backend/.env ps"
}
finally {
    Pop-Location
}
